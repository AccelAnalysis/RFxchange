import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(
  root,
  "src/data/geography/tigerweb-2025-hampton-roads-boundaries.ts",
);
const sourceLayerUrl =
  "https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/State_County/MapServer/1";
const geographies = Object.freeze([
  Object.freeze({ geoid: "51740", geographyId: "us-va-portsmouth" }),
  Object.freeze({ geoid: "51710", geographyId: "us-va-norfolk" }),
  Object.freeze({ geoid: "51800", geographyId: "us-va-suffolk" }),
  Object.freeze({ geoid: "51550", geographyId: "us-va-chesapeake" }),
]);
const geometryPrecision = 5;
const maxAllowableOffsetDegrees = 0.0001;
const query = new URL(`${sourceLayerUrl}/query`);
query.search = new URLSearchParams({
  where: `GEOID IN (${geographies.map(({ geoid }) => `'${geoid}'`).join(",")})`,
  outFields: "GEOID,NAME,BASENAME,STATE,COUNTY",
  returnGeometry: "true",
  outSR: "4326",
  geometryPrecision: String(geometryPrecision),
  maxAllowableOffset: String(maxAllowableOffsetDegrees),
  f: "geojson",
}).toString();

const response = await fetch(query);
if (!response.ok) {
  throw new Error(`TIGERweb query failed with HTTP ${response.status}.`);
}
const payload = await response.json();
if (payload.type !== "FeatureCollection" || !Array.isArray(payload.features)) {
  throw new Error("TIGERweb did not return a GeoJSON FeatureCollection.");
}

const byGeoid = new Map(
  payload.features.map((feature) => [String(feature.properties?.GEOID ?? ""), feature]),
);
const retrievedAt = new Date().toISOString();
const features = geographies.map(({ geoid, geographyId }) => {
  const feature = byGeoid.get(geoid);
  if (!feature) throw new Error(`TIGERweb response is missing GEOID ${geoid}.`);
  if (feature.geometry?.type !== "Polygon" && feature.geometry?.type !== "MultiPolygon") {
    throw new Error(`TIGERweb GEOID ${geoid} did not return polygon geometry.`);
  }
  const geometryJson = JSON.stringify(feature.geometry);
  return Object.freeze({
    type: "Feature",
    properties: Object.freeze({
      geographyId,
      geoid,
      name: String(feature.properties?.NAME ?? ""),
      baseName: String(feature.properties?.BASENAME ?? ""),
      stateFips: String(feature.properties?.STATE ?? ""),
      countyFips: String(feature.properties?.COUNTY ?? ""),
      geometrySha256: createHash("sha256").update(geometryJson).digest("hex"),
    }),
    geometry: feature.geometry,
  });
});

const snapshot = Object.freeze({
  schemaVersion: 1,
  type: "FeatureCollection",
  provenance: Object.freeze({
    authority: "United States Census Bureau",
    dataset: "TIGERweb State_County",
    vintage: "2025",
    copyright: "Source: U.S. Census Bureau",
    sourceLayerUrl,
    queryUrl: query.toString(),
    retrievedAt,
    coordinateReferenceSystem: "EPSG:4326",
    geometryPrecision,
    maxAllowableOffsetDegrees,
  }),
  features: Object.freeze(features),
});

const source = `// Generated by scripts/fetch-tigerweb-locality-boundaries.mjs.
// Do not hand-edit geometry. Regenerate from the recorded U.S. Census TIGERweb query.

export const TIGERWEB_2025_HAMPTON_ROADS_BOUNDARIES = ${JSON.stringify(snapshot, null, 2)} as const;
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");

console.log(
  `Wrote ${features.length} authoritative TIGERweb locality boundaries to ${outputPath}.`,
);
